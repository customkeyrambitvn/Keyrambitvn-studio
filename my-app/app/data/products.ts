export type ProductDef = {
  name: string;
  image?: string;
};

/** Product rows; pass strings or `{ name, image? }` when an image exists in `/public/products`. */
function L(...entries: (string | ProductDef)[]): ProductDef[] {
  return entries.map((e) => (typeof e === "string" ? { name: e } : e));
}

